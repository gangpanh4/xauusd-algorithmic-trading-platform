"""
Research Analytics result models.

Represents the computed summary statistics generated by the
ResearchAnalyticsEngine.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(
    slots=True,
    frozen=True,
)
class ResearchAnalyticsResult:
    """
    Immutable summary of research analytics.

    Produced by the ResearchAnalyticsEngine after analyzing
    the completed trade history.
    """

    total_trades: int

    winning_trades: int

    losing_trades: int

    breakeven_trades: int

    win_rate: float

    average_profit: float

    average_probability: float

    average_confidence: float